import { beforeEach, describe, expect, it, vi } from 'vitest'
import type { Card } from '@doggynote/core'
import * as doc from './doc.ts'
import { setToastAction, toastAction } from './toast.ts'
vi.mock('./idb.ts', () => ({ getAll: async () => new Map(), putDocument: async () => {}, clearAll: async () => {} }))
const card = (id: string, extra: Partial<Card> = {}): Card => ({ id,kind:'card',type:'note',boardId:'qa-board',x:10,y:20,w:200,h:60,z:1,color:'none',createdAt:1,content:{md:'original'}, ...extra })
beforeEach(async () => {
  await doc.load({ persist: false, readOnly: false })
  doc.setWriteGuard(() => true)
  doc.loadSnapshot([{id:'qa-board',kind:'board',parentId:null,title:'QA',icon:'paw',color:'none',createdAt:1},card('a'),card('b',{x:300,y:100})])
})
describe('document layout transactions', () => {
  it('can redo creation even though its inverse only stores a tombstone', () => {
    doc.commit([doc.createChange(card('new',{positionLocked:true}))])
    doc.undo(); expect(doc.getCard('new')!.purged).toBe(true)
    doc.redo(); expect(doc.getCard('new')!.purged).toBe(false)
    expect(doc.getCard('new')!.positionLocked).toBe(true)
  })
  it('restores a whole alignment in one Undo and Redo', () => {
    doc.update({a:{y:50},b:{y:50}})
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([50,50])
    doc.undo()
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([20,100])
    doc.redo()
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([50,50])
  })
  it('retires an alignment Undo offer after a later action without losing either history step', () => {
    doc.update({a:{y:50},b:{y:50}})
    setToastAction({label:'Undo',run:()=>doc.undo()})
    // Natural measurements do not replace the action that the feedback offers.
    doc.silent({a:{h:90}})
    expect(toastAction()).not.toBeNull()
    doc.update({a:{x:30}})
    expect(toastAction()).toBeNull()
    doc.undo()
    expect(doc.getCard('a')!.x).toBe(10)
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([50,50])
    doc.undo()
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([20,100])
  })
  it('retires old feedback after a user edit amends a newly created card', () => {
    doc.commit([doc.createChange(card('new'))])
    setToastAction({label:'Undo',run:()=>doc.undo()})
    const before=doc.snapshot('new',['content'])
    doc.transient('new',{content:{md:'Initial content'}})
    doc.amendOrCommit('new',before)
    expect(toastAction()).toBeNull()
    doc.undo(); expect(doc.getCard('new')!.purged).toBe(true)
    doc.redo(); expect(doc.getCard('new')!.content).toEqual({md:'Initial content'})
  })
  it('protects transient/committed layout but allows content, measured height and recoverable trash', () => {
    doc.update({a:{positionLocked:true}})
    doc.transient('a',{x:99,w:400}); doc.update({a:{x:999}}); doc.transient('a',{h:999}); doc.update({a:{h:888}})
    expect([doc.getCard('a')!.x,doc.getCard('a')!.w,doc.getCard('a')!.h]).toEqual([10,200,60])
    doc.update({a:{content:{md:'edited while locked'}}})
    doc.silent({a:{h:250}})
    expect(doc.getCard('a')!.content).toEqual({md:'edited while locked'})
    expect(doc.getCard('a')!.h).toBe(250)
    doc.update({a:{deletedAt:1}}); expect(doc.getCard('a')!.deletedAt).toBe(1)
    doc.undo(); expect(doc.getCard('a')!.deletedAt).toBeNull()
    expect(doc.getCard('a')!.positionLocked).toBe(true)
    doc.undo(); expect(doc.getCard('a')!.content).toEqual({md:'original'})
    doc.undo(); expect(doc.getCard('a')!.positionLocked).toBeNull()
  })
  it('does not overwrite newer collaborator geometry or partially undo a group', () => {
    doc.update({a:{y:50},b:{y:50}})
    doc.receiveRemote([card('b',{y:800})])
    doc.undo()
    expect([doc.getCard('a')!.y,doc.getCard('b')!.y]).toEqual([50,800])
  })
  it('refuses read-only and revoked writes/Undo without losing their history', async () => {
    doc.update({a:{x:50}})
    await doc.load({persist:false,readOnly:true})
    doc.undo(); doc.update({a:{positionLocked:true}})
    expect(doc.getCard('a')!.x).toBe(50)
    expect(doc.getCard('a')!.positionLocked).toBeUndefined()
    await doc.load({persist:false,readOnly:false})
    doc.setWriteGuard(()=>false); doc.undo(); expect(doc.getCard('a')!.x).toBe(50)
    doc.setWriteGuard(()=>true); doc.undo(); expect(doc.getCard('a')!.x).toBe(10)
  })
  it('reconciles rejected geometry without dropping unsent null clears or content', async () => {
    await doc.load({persist:true,readOnly:false})
    doc.update({a:{x:50,deletedAt:null,content:{md:'offline content'}}})
    // Include a null clear explicitly in the queue, as happens when unlocking/restoring.
    doc.checkpoint('a',{positionLocked:null} as unknown as Partial<Card>)
    const sent=doc.pendingOutbox()
    doc.reconcileLockedPositions(['a'],[card('a',{positionLocked:true})],sent)
    const pending=doc.pendingOutbox().find((p)=>p.id==='a')!
    expect(pending.patch).not.toHaveProperty('x')
    expect(pending.patch).toHaveProperty('positionLocked',null)
    expect(doc.getCard('a')!.content).toEqual({md:'offline content'})
    await doc.flush()
    await doc.resetLocal()
  })
  it('can combine geometry and a new lock without rejecting an earlier move', () => {
    doc.update({a:{x:80,positionLocked:true}})
    expect(doc.getCard('a')!.x).toBe(80)
    expect(doc.getCard('a')!.positionLocked).toBe(true)
    doc.update({a:{x:99,positionLocked:true}})
    expect(doc.getCard('a')!.x).toBe(80)
  })
  it('pins column geometry on child lock and preserves ordinary member editing', () => {
    doc.loadSnapshot([card('col',{type:'column'}),card('a',{columnId:'col',positionLocked:true}),card('b',{columnId:'col'})])
    doc.update({col:{x:400,w:500}}); doc.transient('b',{columnId:null})
    expect(doc.getCard('col')!.x).toBe(10); expect(doc.getCard('b')!.columnId).toBe('col')
    doc.update({b:{content:{md:'new member content'}}}); expect(doc.getCard('b')!.content).toEqual({md:'new member content'})
    doc.update({a:{positionLocked:false},col:{x:400}}); expect(doc.getCard('col')!.x).toBe(400)
  })
})

it('keeps collapse independently undoable under an inherited column position lock', () => {
  doc.loadSnapshot([card('col',{type:'column',h:1800,content:{title:'References'}}),card('a',{columnId:'col',positionLocked:true,order:1})])
  const before = structuredClone(doc.getCard('a'))
  doc.update({col:{collapsed:true}})
  expect(doc.getCard('col')!.collapsed).toBe(true)
  expect(doc.getCard('col')!.h).toBe(1800)
  doc.undo()
  expect(doc.getCard('col')!.collapsed).toBeNull()
  doc.redo()
  expect(doc.getCard('col')!.collapsed).toBe(true)
  expect(doc.getCard('a')).toEqual(before)
})
