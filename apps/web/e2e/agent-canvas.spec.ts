test('public shares and PNG export use a neutral chat placeholder and never fetch a transcript', async ({ page, browser }, testInfo) => {
  await freshBoard(page, 'Neutral chat export')
  await page.getByTestId('tool-chat').click()
  await waitForSync(page)
  const chatId = await page.locator('[data-type="chat"]').getAttribute('data-card-id')
  const boardId = decodeURIComponent(page.url().split('#/b/')[1])
  const updated = await postSync(page.request, { data: { changes: [{ id: chatId, patch: { content: { title: 'PRIVATE CHAT TOPIC', provider: 'claude' } } }] } })
  expect(updated.ok(), await updated.text()).toBe(true)
  await page.reload()
  await expect(page.locator('[data-type="chat"]')).toContainText('PRIVATE CHAT TOPIC')
  const share = await (await page.request.post('/api/shares', { data: { boardId, permission: 'view' } })).json()
  const token = share.share.token
  const ctx = await browser.newContext({ storageState: { cookies: [], origins: [] } })
  const viewer = await ctx.newPage()
  const requests: string[] = []
  viewer.on('request', (request) => { if (request.url().includes('/api/chats/')) requests.push(request.url()) })
  await viewer.goto(new URL(`/s/${token}`, page.url()).toString())
  await expect(viewer.locator('[data-type="chat"]')).toContainText('Conversation available to board members.')
  await expect(viewer.locator('[data-type="chat"]')).not.toContainText('PRIVATE CHAT TOPIC')
  expect(requests).toEqual([])
  const payload = await ctx.request.get(new URL(`/api/share/${token}`, page.url()).toString())
  expect(await payload.text()).not.toContain('PRIVATE CHAT TOPIC')
  expect((await ctx.request.get(new URL(`/api/chats/${chatId}`, page.url()).toString())).status()).toBe(401)
  await ctx.close()
  await page.evaluate(() => {
    const node = document.querySelector('[data-type="chat"] .chat-card-content')!
    ;(window as any).__exportChatText = []
    const observer = new MutationObserver(() => { (window as any).__exportChatText.push(node.textContent) })
    observer.observe(node, { subtree: true, childList: true, characterData: true })
    ;(window as any).__exportChatObserver = observer
  })
  await page.getByTestId('board-more').click()
  await page.getByTestId('export').click()
  const downloaded = page.waitForEvent('download')
  await page.getByTestId('export-go').click()
  const image = await downloaded
  expect(image.suggestedFilename()).toMatch(/\.png$/)
  await image.saveAs(`../../docs/qa/agent-canvas/screenshots/export-neutral-${testInfo.project.name}.png`)
  const observed = await page.evaluate(() => { (window as any).__exportChatObserver.disconnect(); return (window as any).__exportChatText as string[] })
  expect(observed.some((text) => text.includes('Conversation available to board members.') && !text.includes('PRIVATE CHAT TOPIC'))).toBe(true)
})

test('dragging into a chat adds an explicit context link while an existing visual line stays decorative', async ({ page }) => {
  await freshBoard(page, 'Context connector semantics')
  const source = await addNote(page, 'Drag source', 0.25, 0.3)
  const from = await source.getAttribute('data-card-id')
  await page.getByTestId('tool-chat').click()
  const chat = page.locator('[data-type="chat"]')
  const to = await chat.getAttribute('data-card-id')
  await waitForSync(page)
  const boardId = decodeURIComponent(page.url().split('#/b/')[1])
  const visualId = crypto.randomUUID()
  const visual = await postSync(page.request, { data: { changes: [{ id: visualId, patch: { id: visualId, kind: 'connection', boardId, from, to, arrow: 'end', createdAt: Date.now() } }] } })
  expect(visual.ok(), `${visual.status()}: ${await visual.text()}`).toBe(true)
  await expect.poll(async () => (await (await page.request.get(`/api/chats/${to}/context`)).json()).context.sources.length).toBe(0)
  await source.hover()
  const handle = (await source.getByTestId('connect-handle-right').boundingBox())!
  const destination = (await chat.boundingBox())!
  await page.mouse.move(handle.x + 7, handle.y + 7)
  await page.mouse.down()
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height / 2, { steps: 10 })
  await page.mouse.up()
  await waitForSync(page)
  await expect.poll(async () => (await (await page.request.get(`/api/chats/${to}/context`)).json()).context.sources.length).toBe(1)
  await page.getByTestId('undo').click()
  await waitForSync(page)
  await expect.poll(async () => (await (await page.request.get(`/api/chats/${to}/context`)).json()).context.sources.length).toBe(0)
  await page.getByTestId('redo').click()
  await waitForSync(page)
  await expect.poll(async () => (await (await page.request.get(`/api/chats/${to}/context`)).json()).context.sources.length).toBe(1)
})

test('a shared viewer can read saved history, cannot send, and loses transcript access after revocation', async ({ page, browser }) => {
  await freshBoard(page, 'Shared conversation permissions')
  await page.getByTestId('tool-chat').click()
  await waitForSync(page)
  const chatId = await page.locator('[data-type="chat"]').getAttribute('data-card-id')
  const boardId = decodeURIComponent(page.url().split('#/b/')[1])
  // A view grant cannot downgrade the fixture's inherited edit access to legacy home.
  expect((await postSync(page.request, { data: { changes: [{ id: boardId, patch: { parentId: null } }] } })).ok()).toBe(true)
  const capture = await (await page.request.get(`/api/chats/${chatId}/context`)).json()
  const begin = { operationId: crypto.randomUUID(), deviceId: 'owner-fixture', runKey: 's'.repeat(40), expectedRevision: 0, provider: 'claude', contextVersion: capture.version, prompt: 'A shared prompt' }
  expect((await page.request.post(`/api/chats/${chatId}/turns`, { data: begin })).status()).toBe(201)
  expect((await page.request.post(`/api/chats/${chatId}/turns/${begin.operationId}/finish`, { data: { deviceId: begin.deviceId, runKey: begin.runKey, status: 'completed', answer: 'A saved answer for board members.' } })).ok()).toBe(true)
  expect((await page.request.post(`/api/boards/${boardId}/members`, { data: { username: 'fido', permission: 'view', includeChildren: false } })).ok()).toBe(true)
  const context = await browser.newContext({ storageState: { cookies: [], origins: [] }, extraHTTPHeaders: { 'x-doggynote-protocol': '4' } })
  try {
    expect((await context.request.post(new URL('/api/auth/login', page.url()).toString(), { data: { username: 'fido', password: 'fetchfetch' } })).ok()).toBe(true)
    const viewer = await context.newPage()
    await viewer.goto(page.url())
    await viewer.locator('[data-type="chat"]').getByRole('button', { name: 'Open conversation' }).click()
    const dialog = viewer.getByTestId('chat-conversation')
    await expect(dialog).toContainText('A saved answer for board members.')
    await expect(dialog.getByRole('textbox', { name: 'Message', exact: true })).toBeDisabled()
    await expect(dialog.getByRole('button', { name: 'Branch here' })).toHaveCount(0)
    await expect(dialog.getByRole('button', { name: 'Save answer / selection as note' })).toHaveCount(0)
    expect((await viewer.request.post(`/api/chats/${chatId}/turns`, { data: { ...begin, operationId: crypto.randomUUID(), expectedRevision: 2 } })).status()).toBe(403)
    const membersResponse = await page.request.get(`/api/shares?boardId=${boardId}`)
    expect(membersResponse.ok()).toBe(true)
    const members = await membersResponse.json()
    const member = members.members.find((item: { username: string }) => item.username === 'fido')
    expect(member).toBeTruthy()
    expect((await page.request.delete(`/api/boards/${boardId}/members/${member.id}`)).ok()).toBe(true)
    expect((await viewer.request.get(`/api/chats/${chatId}`)).status()).toBe(403)
    expect((await viewer.request.get(`/api/chats/${chatId}/context`)).status()).toBe(403)
    await viewer.reload()
    await expect(viewer.getByTestId('chat-conversation')).toHaveCount(0)
    await expect(viewer.locator('[data-type="chat"]')).toHaveCount(0)
  } finally { await context.close() }
})
