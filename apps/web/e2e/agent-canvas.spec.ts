test('area conversations read updated synced-note context and place saved outputs correctly', async ({ page }) => {
  await freshBoard(page, 'Conversation with current main features')
  const url = page.url()
  const original = await addNote(page, 'Shared launch brief', 0.25, 0.3)
  const sourceId = await original.getAttribute('data-card-id')
  await openCardMenu(page, original)
  await page.getByTestId('canvas-context-menu').getByRole('menuitem', { name: 'Make a synced copy' }).click()
  const copy = page.locator('[data-type="note"]').filter({ has: page.locator('[data-testid="synced-marker"]') }).last()
  await expect(page.getByTestId('synced-marker')).toHaveCount(2)
  await copy.dblclick()
  await page.getByTestId('note-editor').fill('Updated shared launch brief')
  await page.keyboard.press('Escape')
  await expect(original).toContainText('Updated shared launch brief')
  await original.click()
  await page.getByTestId('ask-selection').click()
  const dialog = page.getByTestId('chat-conversation')
  const chatId = await page.locator('[data-type="chat"]').getAttribute('data-card-id')
  await dialog.getByRole('button', { name: 'Close conversation' }).click()
  await page.keyboard.press('ControlOrMeta+a')
  await page.getByTestId('area-from-selection').click()
  await page.getByTestId('area-title-input').fill('Launch context')
  await page.keyboard.press('Enter')
  const areaId = await page.locator('[data-type="area"]').getAttribute('data-card-id')
  await waitForSync(page)
  await page.goto(`${url}?chat=${chatId}`)
  await dialog.getByRole('button', { name: 'Inspect context (1)' }).click()
  await expect(dialog.getByRole('complementary')).toContainText('Updated shared launch brief')
  const inspected = await (await page.request.get(`/api/chats/${chatId}/context`)).json()
  expect(inspected.context.sources).toHaveLength(1)
  expect(inspected.context.sources[0]).toMatchObject({ id: sourceId, text: 'Updated shared launch brief' })
  await dialog.getByRole('button', { name: 'Back to thread' }).click()
  const begin = { operationId: crypto.randomUUID(), deviceId: 'area-fixture', runKey: 'a'.repeat(40), expectedRevision: 0, provider: 'claude', contextVersion: inspected.version, prompt: 'Make one task' }
  const response = await page.request.post(`/api/chats/${chatId}/turns`, { data: begin })
  expect(response.status(), await response.text()).toBe(201)
  expect((await page.request.post(`/api/chats/${chatId}/turns/${begin.operationId}/finish`, { data: { deviceId: begin.deviceId, runKey: begin.runKey, status: 'completed', answer: '- Book the park' } })).ok()).toBe(true)
  await page.reload()
  await expect(dialog.getByTestId('chat-turn')).toContainText('Book the park')
  await dialog.getByRole('button', { name: 'Save answer / selection as note' }).click()
  await page.getByTestId('toast').getByRole('button', { name: 'Show note' }).click()
  await waitForSync(page)
  const snapshot = (await pullAllObjects(page.request)).objects.filter(o => o.boardId === url.split('/b/')[1])
  const chat = snapshot.find(o => o.id === chatId), area = snapshot.find(o => o.id === areaId)
  const saved = snapshot.find(o => o.type === 'note' && o.id.startsWith('answer-'))
  expect(chat.areaId).toBe(areaId)
  expect(saved.x).toBeGreaterThanOrEqual(area.x + chat.x + chat.w + 40)
  await page.goto(`${url}?chat=${chatId}`)
  await page.reload()
  await dialog.getByRole('button', { name: 'Propose to-do list' }).click()
  await page.getByRole('button', { name: 'Review on board' }).click()
  await expect(page.getByTestId('proposal-banner')).toBeVisible()
  await page.getByTestId('proposal-approve').click()
  await expect(page.getByTestId('proposal-banner')).toHaveCount(0)
  const task = (await pullAllObjects(page.request)).objects.find(o => o.type === 'todo' && o.boardId === chat.boardId)
  expect(task.areaId).toBe(areaId)
  expect(task.x).toBe(chat.x + chat.w + 40)
})

