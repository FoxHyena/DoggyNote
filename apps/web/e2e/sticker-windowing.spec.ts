import { expect, test } from '@playwright/test'
import { openStickerTray, stickerBoard } from './sticker-helpers.ts'
import { hundredStickerPack } from './sticker-windowing.ts'

test('a cold 100-sticker preview keeps pending tiles stable and only mounts nearby artwork', async ({ page, request }) => {
  await stickerBoard(page, request)
  const { pack, requested } = await hundredStickerPack(page, true)
  await openStickerTray(page)
  const tray = page.getByTestId('sticker-tray')
  await tray.getByRole('button', { name: 'Add pack', exact: true }).first().click()
  await tray.getByLabel('Pack link or short name').fill('DoggyFixture')
  await tray.getByRole('button', { name: 'Preview pack', exact: true }).click()
  const tile = tray.locator(`[data-sticker-asset="${pack.stickers[8].assetId}"]`), original = await tile.elementHandle()
  await expect(tray.getByText('100 stickers · 100 ready', { exact: true })).toBeVisible()
  expect(await original!.evaluate((el) => el.isConnected)).toBe(true)
  await expect(tray.locator('.sticker-grid')).toHaveAttribute('data-sticker-count', '100')
  expect(await tray.getByTestId('sticker-pick').count()).toBeLessThanOrEqual(28)
  expect(requested.size).toBeLessThanOrEqual(28)

  // A pressed tile cannot unmount as its scroll window changes.
  await tile.dispatchEvent('pointerdown', { pointerId: 7, button: 0, pointerType: 'touch', isPrimary: true })
  await tray.locator('.sticker-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight })
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[99].assetId}"]`)).toBeAttached()
  expect(await original!.evaluate((el) => el.isConnected)).toBe(true)
  await tile.dispatchEvent('pointercancel', { pointerId: 7, pointerType: 'touch' })
  await expect(tile).toHaveCount(0)
})

test('a 100-sticker collection restores scroll and preview focus, navigates beyond the window, and survives refresh', async ({ page, request, browserName }) => {
  await stickerBoard(page, request)
  const { pack, requested } = await hundredStickerPack(page)
  await openStickerTray(page)
  const tray = page.getByTestId('sticker-tray')
  await tray.getByRole('button', { name: pack.title, exact: true }).click()
  expect(await tray.getByTestId('sticker-pick').count()).toBeLessThanOrEqual(28)
  expect(requested.size).toBeLessThanOrEqual(28)
  const first = tray.getByTestId('sticker-pick').first(), original = await first.elementHandle()
  // Change an unrelated entry during a refresh, while keeping the tile itself.
  pack.stickers[99].error = 'unrelated metadata update'
  const refreshed = page.waitForResponse((response) => new URL(response.url()).pathname === '/api/stickers')
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await (await refreshed).finished()
  await expect.poll(() => original!.evaluate((el) => el.isConnected)).toBe(true)
  await first.focus()
  for (let i = 0; i < 32; i++) await page.keyboard.press('Tab')
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[32].assetId}"]`)).toBeFocused()
  await page.keyboard.press('End')
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[99].assetId}"]`)).toBeFocused()
  // macOS WebKit uses Option-Tab to include buttons in native focus traversal.
  const forward = browserName === 'webkit' ? 'Alt+Tab' : 'Tab', backward = browserName === 'webkit' ? 'Alt+Shift+Tab' : 'Shift+Tab'
  await page.keyboard.press(forward)
  expect(await tray.locator('.sticker-grid').evaluate((el) => el.contains(document.activeElement))).toBe(false)
  await tray.locator('.sticker-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight / 2 })
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[99].assetId}"]`)).toHaveCount(0)
  await page.keyboard.press(backward)
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[99].assetId}"]`)).toBeFocused()
  await page.keyboard.press('Home'); await page.keyboard.press(backward)
  await tray.locator('.sticker-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight / 2 })
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[0].assetId}"]`)).toHaveCount(0)
  await page.keyboard.press(forward)
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[0].assetId}"]`)).toBeFocused()
  for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowDown')
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[32].assetId}"]`)).toBeFocused()
  const scroll = tray.locator('.sticker-scroll'), at = await scroll.evaluate((el) => el.scrollTop)
  expect(at).toBeGreaterThan(0)
  await page.keyboard.press('Space')
  await tray.getByTestId('sticker-preview-back').click()
  await expect(tray.locator(`[data-sticker-asset="${pack.stickers[32].assetId}"]`)).toBeFocused()
  await expect.poll(() => scroll.evaluate((el) => el.scrollTop)).toBe(at)
  await tray.getByRole('button', { name: 'Close stickers', exact: true }).click()
  await openStickerTray(page)
  await expect.poll(() => scroll.evaluate((el) => el.scrollTop)).toBe(at)
  await tray.getByLabel('Search your stickers').fill('no match anywhere')
  await expect(tray.getByText('No stickers found', { exact: true })).toBeVisible()
  await tray.getByLabel('Search your stickers').fill('')
  await expect(tray.locator('.sticker-grid')).toHaveAttribute('data-sticker-count', '100')
})
