test('twenty members collapse without data loss, hidden hits or reordering; Undo, reload and search reveal restore context', async ({ page }) => {
  const f = await fixture(page)
  await expect(f.column.locator('.column-meta')).toHaveText('20 cards')
  const child = page.locator(`[data-card-id="${f.kids[0]!.id}"]`)
  await child.click()
  await expect(child).toHaveClass(/selected/)
  // Height measurement has its own debounce; wait for it before comparing records.
  const heights = await f.column.getByTestId('card').evaluateAll((els) => Object.fromEntries(els.map((el) => [(el as HTMLElement).dataset.cardId, (el as HTMLElement).offsetHeight])))
  await expect.poll(async () => {
    const snapshot = await boardSnapshot(page, f.boardId)
    return f.kids.every((kid) => snapshot.find((o: { id: string }) => o.id === kid.id)?.h === heights[kid.id])
  }).toBe(true)
  await waitForSync(page)
  const before = await boardSnapshot(page, f.boardId)
  const nearby = page.locator(`[data-card-id="${f.outside}"]`)
  const beforeBox = await nearby.boundingBox()
  const line = page.locator(`[data-connection-id="${f.prefix}-external"]`)
  const oldPath = await line.locator('.conn-line').getAttribute('d')
  await f.toggle.click()
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(f.column.getByTestId('card')).toHaveCount(0)
  await expect(f.column).toHaveClass(/selected/)
  expect((await f.column.boundingBox())!.height).toBe(58)
  expect(await nearby.boundingBox()).toEqual(beforeBox)
  await expect(line).toHaveAttribute('data-collapsed-endpoint', 'true')
  await expect(page.locator(`[data-connection-id="${f.prefix}-internal"]`)).toHaveCount(0)
  await waitForSync(page)
  const after = await boardSnapshot(page, f.boardId)
  for (const kid of f.kids) expect(after.find((o: { id: string }) => o.id === kid.id)).toEqual(before.find((o: { id: string }) => o.id === kid.id))
  expect(after.find((o: { id: string }) => o.id === f.col).h).toBe(before.find((o: { id: string }) => o.id === f.col).h)
  // The old child position is now empty space. It cannot lift a hidden reference.
  await page.mouse.move(100, 230)
  await page.mouse.down()
  await page.mouse.move(160, 270, { steps: 5 })
  await page.mouse.up()
  await page.keyboard.press(`${MOD}+z`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(line.locator('.conn-line')).toHaveAttribute('d', oldPath!)
  await page.keyboard.press(`${MOD}+Shift+z`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await dragBy(page, nearby, 40, 20)
  await waitForSync(page)
  await page.reload()
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await page.getByTestId('open-fetch').click()
  await page.getByTestId('fetch-input').fill(f.kids[19]!.content.md)
  await page.keyboard.press('Enter')
  const last = page.locator(`[data-card-id="${f.kids[19]!.id}"]`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(last).toBeInViewport()
  await expect(last).toHaveClass(/selected/)
  await expect(last).toBeFocused()
  await page.keyboard.press(`${MOD}+z`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(f.toggle).toBeInViewport()
  await expect(f.toggle).toBeFocused()
})

test('keyboard toggle, empty column, offline persistence and concurrent title edits stay independent', async ({ page }) => {
  const f = await fixture(page, 0)
  await expect(f.column.locator('.column-meta')).toHaveText('0 cards')
  await f.toggle.focus()
  await page.keyboard.press('Space')
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(f.toggle).toBeFocused()
  await waitForSync(page)
  await page.context().setOffline(true)
  await page.keyboard.press('Enter')
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'true')
  await page.context().setOffline(false)
  await waitForSync(page)
  const renamed = await postSync(page.request, { data: { changes: [{ id: f.col, patch: { content: { title: 'Concurrent renamed references' } } }] } })
  expect(renamed.ok()).toBe(true)
  await f.toggle.click()
  await waitForSync(page)
  await page.reload()
  await expect(f.column.getByTestId('column-title')).toHaveText('Concurrent renamed references')
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
})

test('read-only exploration expands locally with no queued mutation and restores stored view after reload', async ({ page, browser }) => {
  const f = await fixture(page, 3)
  await f.toggle.click()
  await waitForSync(page)
  const response = await page.request.post('/api/shares', { data: { boardId: f.boardId, permission: 'view' } })
  expect(response.ok()).toBe(true)
  const { share } = await response.json()
  const viewer = await browser.newContext({ storageState: { cookies: [], origins: [] } })
  const v = await viewer.newPage()
  await v.goto(`/s/${share.token}`)
  const toggle = v.getByTestId('column-toggle')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  const writes: string[] = []
  v.on('request', (r) => { if (r.method() !== 'GET' && r.url().includes('/api/')) writes.push(r.url()) })
  await toggle.click()
  await expect(v.locator('.in-column')).toHaveCount(3)
  expect(writes).toEqual([])
  await v.reload()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  const denied = await v.request.post('/api/sync', { data: { changes: [{ id: f.col, patch: { collapsed: false } }] } })
  expect([401, 403]).toContain(denied.status())
  await viewer.close()
})

test('PNG export reflects the collapsed view and preserves hidden members for later expansion', async ({ page }, testInfo) => {
  const f = await fixture(page, 3)
  await f.toggle.click()
  await waitForSync(page)
  async function exportImage(name: string) {
    await page.getByTestId('board-more').click()
    await page.getByTestId('export').click()
    await expect(page.getByTestId('export-panel')).toContainText('Columns export as currently shown')
    await page.getByTestId('export-scale-1').click()
    const download = page.waitForEvent('download')
    await page.getByTestId('export-go').click()
    const image = await download
    await image.saveAs(testInfo.outputPath(name))
    const { readFile } = await import('node:fs/promises')
    const bytes = await readFile(testInfo.outputPath(name))
    return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }
  }
  const collapsed = await exportImage('collapsed.png')
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await f.toggle.click()
  const expanded = await exportImage('expanded.png')
  expect(expanded.width).toBe(collapsed.width)
  expect(expanded.height).toBeGreaterThan(collapsed.height)
  await expect(f.column.locator('.in-column')).toHaveCount(3)
})

test('locked member allows collapse while alignment uses the visible header and preserves the column family', async ({ page }) => {
  const f = await fixture(page, 3)
  const child = page.locator(`[data-card-id="${f.kids[0]!.id}"]`)
  await child.click()
  await page.getByTestId('position-lock').click()
  await waitForSync(page)
  await test.step('header disclosure stays reachable above a selected locked first member', async () => {
    await expect(page.getByTestId('selection-column-toggle')).toHaveCount(0)
    await f.toggle.click()
    await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  })
  await expect(page.getByTestId('unlock-column-layout')).toHaveCount(0)
  // Collapse slides shut; measure once it has settled on the header.
  await expect.poll(async () => (await f.column.boundingBox())!.height).toBe(58)
  const original = await f.column.boundingBox()
  await dragBy(page, f.column.getByTestId('column-title'), 80, 40)
  const afterDrag = await f.column.boundingBox()
  expect(afterDrag!.x).toBe(original!.x)
  expect(afterDrag!.y).toBe(original!.y)
  // The selection envelope includes locked cards. Put the movable note above
  // the header so its visible 58px bottom is the reference edge, not the note.
  await page.keyboard.press('Escape')
  const nearby = page.locator(`[data-card-id="${f.outside}"]`)
  await dragBy(page, nearby, 0, -60)
  const beforeAlignment = await nearby.boundingBox()
  expect(beforeAlignment!.y + beforeAlignment!.height).toBeLessThan(original!.y + original!.height)
  expect((await f.column.boundingBox())!.height).toBe(58)
  await page.keyboard.press(`${MOD}+a`)
  await page.getByTestId('align-bottom').click()
  await expect.poll(async () => {
    const a = await f.column.boundingBox(), b = await nearby.boundingBox()
    return Math.abs(a!.y + a!.height - b!.y - b!.height)
  }).toBeLessThan(1)
  expect(await f.column.boundingBox()).toEqual(original)
  await page.keyboard.press(`${MOD}+z`)
  expect(await nearby.boundingBox()).toEqual(beforeAlignment)
  await f.toggle.click()
  await expect(f.column.locator('.in-column')).toHaveCount(3)
  const snapshot = await boardSnapshot(page, f.boardId)
  for (const k of f.kids) expect(snapshot.find((o: { id: string }) => o.id === k.id).order).toBe(k.order)
})

test('two authorized sessions converge on collapse and concurrent title edits without losing either field', async ({ page, browser }) => {
  test.setTimeout(60_000)
  const f = await fixture(page, 3)
  const context = await browser.newContext({ storageState: await page.context().storageState() })
  const other = await context.newPage()
  await other.goto(page.url())
  const otherCol = other.locator(`[data-card-id="${f.col}"]`)
  await expect(otherCol).toBeVisible()
  await otherCol.getByTestId('column-title').click()
  await other.keyboard.press('Enter')
  await expect(other.getByTestId('column-title-input')).toBeVisible()
  await other.getByTestId('column-title-input').fill('Shared references renamed in another session')
  await f.toggle.click()
  await other.keyboard.press('Escape')
  await waitForSync(page)
  await waitForSync(other)
  // Focus refreshes access and pulls without relying on a timing retry of the task.
  await other.bringToFront()
  await expect(otherCol.getByTestId('column-toggle')).toHaveAttribute('aria-expanded', 'false', { timeout: 15_000 })
  await page.bringToFront()
  await expect(f.column.getByTestId('column-title')).toHaveText('Shared references renamed in another session', { timeout: 15_000 })
  await f.toggle.click()
  await waitForSync(page)
  await expect(otherCol.locator('.in-column')).toHaveCount(3, { timeout: 15_000 })
  await context.close()
})

