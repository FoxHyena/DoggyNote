  await waitForSync(page)
  expect((await pullAllObjects(page.request)).objects.find(o=>o.id===note).areaId).toBeNull()
  await page.keyboard.press(`${MOD}+z`)
  await waitForSync(page)
  expect((await pullAllObjects(page.request)).objects.find(o=>o.id===note).areaId).toBe(area)
