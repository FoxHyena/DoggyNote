test('offline removal survives restart and safely detaches a concurrent join over the 200-object push limit',async({page})=>{
  test.setTimeout(60000)
  await freshBoard(page,'Durable area removal')
  const board=page.url().split('/b/')[1]!, prefix=crypto.randomUUID().slice(0,8),areaId=`${prefix}-area`
  const base={kind:'card',boardId:board,x:24,y:72,w:240,h:90,z:1,color:'none',createdAt:Date.now(),columnId:null,areaId}
  const area={...base,id:areaId,type:'area',areaId:null,x:40,y:40,w:900,h:500,content:{title:'Large project'}}
  expect((await postSync(page.request,{data:{changes:[{id:areaId,patch:area}]}})).ok()).toBe(true)
  const notes=Array.from({length:230},(_,i)=>({...base,id:`${prefix}-${i}`,type:'todo',content:{title:`Context ${i}`,items:[]},x:24+(i%10)*300,y:72+Math.floor(i/10)*150}))
  for(let i=0;i<notes.length;i+=200)expect((await postSync(page.request,{data:{changes:notes.slice(i,i+200).map(o=>({id:o.id,patch:o}))}})).ok()).toBe(true)
  await page.evaluate(id=>localStorage.setItem(`doggynote.cam.${id}`,JSON.stringify({x:0,y:0,zoom:1})),board)
  await page.reload();const areaEl=page.locator(`[data-card-id="${areaId}"]`)
  await expect(areaEl).toBeVisible();await waitForSync(page)
  // The large family's controls stay at the area's right edge; pan to reach them.
  const canvas=(await page.getByTestId('canvas').boundingBox())!,more=(await areaEl.getByTestId('area-more').boundingBox())!
  await page.mouse.move(canvas.x+canvas.width/2,canvas.y+20)
  await page.mouse.wheel(more.x-canvas.x-canvas.width+80,0)
  await expect(areaEl.getByTestId('area-more')).toBeInViewport()
  // Only sync pushes fail; a reload still loads real assets and the persisted outbox.
  await page.route('**/api/sync',route=>route.request().method()==='POST'?route.abort('internetdisconnected'):route.continue())
  await areaEl.getByTestId('area-more').click();await page.getByTestId('area-more-menu').getByRole('menuitem',{name:'Remove area, keep contents'}).click()
  await expect.poll(()=>page.getByTestId('sync-status').getAttribute('data-pending'),{timeout:15000}).toBe('231')
  await page.reload();await expect(areaEl).toHaveCount(0)
  await expect.poll(()=>page.getByTestId('sync-status').getAttribute('data-pending'),{timeout:15000}).toBe('231')
  const joined={...base,id:`${prefix}-joined`,type:'todo',content:{title:'Joined during removal',items:[]}}
  expect((await postSync(page.request,{data:{changes:[{id:joined.id,patch:joined}]}})).ok()).toBe(true)
  await page.unroute('**/api/sync')
  await page.context().setOffline(true);await page.context().setOffline(false)
  await waitForSync(page)
  const rows=(await pullAllObjects(page.request)).objects.filter(o=>o.boardId===board)
  expect(rows.find(o=>o.id===areaId).deletedAt).toBeTruthy()
  expect(rows.filter(o=>o.kind==='card'&&o.id!==areaId&&!o.deletedAt&&!o.purged)).toHaveLength(231)
  expect(rows.filter(o=>o.areaId===areaId&&!o.deletedAt&&!o.purged)).toHaveLength(0)
  expect(rows.find(o=>o.id===joined.id)).toMatchObject({x:64,y:112,areaId:null})
})

