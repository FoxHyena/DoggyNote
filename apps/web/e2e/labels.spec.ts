test('create, reuse, multi-apply, rename, recolor, remove and Undo/Redo labels using real input', async ({ page }) => {
  await freshBoard(page, `Labels ${crypto.randomUUID().slice(0, 8)}`)
  const first = await addNote(page, 'Warm side lighting reference', .35, .35)
  await first.click()
  await page.keyboard.press('Escape')
  await page.getByTestId('labels-button').click()
  await page.getByLabel('Label name', { exact: true }).fill('Lighting')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(first.locator('.label-chip')).toHaveText('Lighting')
  await expect(page.getByLabel('Apply Lighting', { exact: true })).toBeChecked()
  // Typing an existing name finds it instead of offering a duplicate.
  await page.getByLabel('Label name', { exact: true }).fill(' lighting ')
  await expect(page.getByRole('button', { name: 'Create', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Apply Lighting', { exact: true })).toBeVisible()
  await page.getByLabel('Close labels').click()
  const second = await addNote(page, 'Unresolved opening scene question', .65, .6)
  await first.click()
  await page.keyboard.press('Escape')
  await second.click({ modifiers: ['Shift'] })
  await page.getByTestId('labels-button').click()
  const apply = page.getByLabel('Apply Lighting', { exact: true })
  await expect(apply).not.toBeChecked()
  await apply.check()
  await expect(first.locator('.label-chip')).toHaveText('Lighting')
  await expect(second.locator('.label-chip')).toHaveText('Lighting')
  await page.getByLabel('Rename Lighting', { exact: true }).click()
  await page.getByLabel('New name for Lighting', { exact: true }).fill('Lighting references')
  await page.getByRole('button', { name: 'Save name' }).click()
  await page.getByLabel('Colour for Lighting references').click()
  await page.getByRole('group', { name: 'Colours for Lighting references' }).getByRole('button', { name: 'Gold' }).click()
  await expect(first.locator('.label-chip')).toHaveText('Lighting references')
  await expect(second.locator('.label-chip')).toHaveText('Lighting references')
  await page.getByLabel('Remove Lighting references from board').click()
  await expect(first.locator('.label-chip')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo label change' }).click()
  await expect(first.locator('.label-chip')).toHaveText('Lighting references')
  await page.getByRole('button', { name: 'Redo label change' }).click()
  await expect(first.locator('.label-chip')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo label change' }).click()
  await page.getByLabel('Close labels').click()
  await waitForSync(page)
  await page.reload()
  await expect(cardByText(page, 'Warm side lighting reference').locator('.label-chip')).toHaveText('Lighting references')
})

