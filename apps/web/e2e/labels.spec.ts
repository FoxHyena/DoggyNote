test('different label memberships and metadata fields merge across sessions and offline reconnect', async ({ page, context }) => {
  await freshBoard(page)
  const first = await addNote(page, 'Concurrent reference')
  await first.click()
  await page.keyboard.press('Escape')
  await page.getByTestId('labels-button').click()
  for (const name of ['Lighting', 'Question']) {
    await page.getByLabel('Label name', { exact: true }).fill(name)
    await page.getByRole('button', { name: 'Create', exact: true }).click()
  }
  await page.getByLabel('Close labels').click()
  await waitForSync(page)
  const peer = await context.newPage()
  await peer.goto(page.url())
  await expect(cardByText(peer, 'Concurrent reference').locator('.label-chip')).toHaveCount(2)
  await first.click()
  await page.keyboard.press('Escape')
  await page.getByTestId('labels-button').click()
  await page.getByLabel('Rename Lighting', { exact: true }).click()
  await page.getByLabel('New name for Lighting', { exact: true }).fill('Lighting references')
  await page.getByRole('button', { name: 'Save name' }).click()
  await page.getByLabel('Close labels').click()
  await waitForSync(page)
  await peer.bringToFront()
  await peer.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(cardByText(peer, 'Concurrent reference').locator('.label-chip').filter({ hasText: 'Lighting references' })).toBeVisible()
  await context.setOffline(true)
  await first.click()
  await page.keyboard.press('Escape')
  await page.getByTestId('labels-button').click()
  await page.getByLabel('Apply Question', { exact: true }).uncheck()
  await page.getByLabel('Close labels').click()
  await expect(first.locator('.label-chip')).toHaveText('Lighting references')
  await context.setOffline(false)
  await waitForSync(page)
  await page.reload()
  await expect(cardByText(page, 'Concurrent reference').locator('.label-chip')).toHaveText('Lighting references')
  await peer.close()
})

test('read-only, private capture and revoked access protect label metadata and cached search', async ({ page, browser }) => {
  await freshBoard(page)
  const boardId = decodeURIComponent(new URL(page.url()).hash.split('/')[2])
  expect((await postSync(page.request, { data: { changes: [{ id: boardId, patch: { parentId: null } }] } })).ok()).toBe(true)
  await page.reload()
  await expect(page.getByTestId('canvas')).toBeVisible()
  const card = await addNote(page, 'Accessible reference body')
  await card.click()
  await page.keyboard.press('Escape')
  await page.getByTestId('labels-button').click()
  await page.getByLabel('Label name', { exact: true }).fill('LightingPrivateBoundary')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByLabel('Close labels').click()
  await waitForSync(page)
  const owner = (await (await page.request.get('/api/me')).json()).user
  const token = 'd'.repeat(32)
  const privateCard = crypto.randomUUID()
  expect((await postSync(page.request, { data: { changes: [
    { id: `toybox:${owner.id}`, patch: { id: `toybox:${owner.id}`, kind: 'board', parentId: null, title: 'Private Inbox', icon: 'paw', color: 'none', createdAt: Date.now(), [`labelName${token}`]: 'PrivateCaptureSecret' } },
    { id: privateCard, patch: { id: privateCard, kind: 'card', type: 'note', boardId: `toybox:${owner.id}`, x: 0, y: 0, w: 260, h: 80, z: 1, color: 'none', content: { md: 'Private capture body' }, createdAt: Date.now(), [`label${token}`]: true } },
  ] } })).ok()).toBe(true)
  const other = await browser.newContext({ storageState: { cookies: [], origins: [] }, extraHTTPHeaders: { 'x-doggynote-protocol': '2' } })
  try {
    expect((await other.request.post('/api/auth/login', { data: { username: 'fido', password: 'fetchfetch' } })).ok()).toBe(true)
    const shared = await page.request.post(`/api/boards/${boardId}/members`, { data: { username: 'fido', permission: 'view', includeChildren: false } })
    expect(shared.status()).toBe(201)
    const viewer = await other.newPage()
    await viewer.goto(`/#/b/${boardId}`)
    await expect(cardByText(viewer, 'Accessible reference body').locator('.label-chip')).toHaveText('LightingPrivateBoundary')
    await expect(viewer.getByTestId('labels-button')).toHaveCount(0)
    const objects = (await pullAllObjects(other.request)).objects
    expect(JSON.stringify(objects)).not.toContain('PrivateCaptureSecret')
    const metadata = objects.find((o: { id: string }) => o.id === boardId)
    const nameKey = Object.keys(metadata).find((k) => k.startsWith('labelName'))!
    expect((await other.request.post('/api/sync', { data: { changes: [{ id: boardId, patch: { [nameKey]: 'Forbidden rename' } }] } })).status()).toBe(403)
    await viewer.getByTestId('open-fetch').click()
    await viewer.getByTestId('fetch-input').fill('LightingPrivateBoundary')
    await expect(viewer.getByTestId('fetch-hit')).toHaveCount(1)
    const members = await (await page.request.get(`/api/shares?boardId=${boardId}`)).json()
    const member = members.members.find((m: { userId: string }) => m.userId !== owner.id)
    expect((await page.request.delete(`/api/boards/${boardId}/members/${member.id}`)).ok()).toBe(true)
    await viewer.getByTestId('fetch-input').press('Enter')
    await expect(viewer.getByTestId('fetch-hit')).toHaveCount(0)
    await viewer.getByTestId('fetch-input').fill('PrivateCaptureSecret')
    await expect(viewer.getByTestId('fetch-hit')).toHaveCount(0)
  } finally { await other.close() }
})

test('cross-board label jump reveals and focuses a real member inside a collapsed column', async ({ page }) => {
  const { columnFixture } = await import('./column-fixture.ts')
  const f = await columnFixture(page, 20)
  const marker = crypto.randomUUID().slice(0, 8)
  const targetText = `Reference 20: isolated label reveal ${marker}`
  const columnTitle = `Twenty references for label reveal ${marker}`
  const labelName = `Lighting hidden references ${marker}`
  const seeded = await postSync(page.request, { data: { changes: [
    { id: f.kids[19]!.id, patch: { content: { md: targetText } } },
    { id: f.col, patch: { content: { title: columnTitle } } },
  ] } })
  expect(seeded.ok(), await seeded.text()).toBe(true)
  await page.reload()
  await page.getByTestId('open-fetch').click()
  await page.getByTestId('fetch-input').fill(targetText)
  await page.getByTestId('fetch-input').press('Enter')
  const target = page.locator(`[data-card-id="${f.kids[19]!.id}"]`)
  await expect(target).toBeInViewport()
  await page.getByTestId('labels-button').click()
  await page.getByLabel('Label name', { exact: true }).fill(labelName)
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByLabel('Close labels').click()
  await page.getByTestId('open-fetch').click()
  await page.getByTestId('fetch-input').fill(columnTitle)
  await page.getByTestId('fetch-input').press('Enter')
  await f.toggle.click()
  await expect(target).toHaveCount(0)
  await waitForSync(page)
  await freshBoard(page, `Search origin ${crypto.randomUUID().slice(0, 8)}`)
  await page.getByTestId('open-fetch').click()
  await page.getByTestId('fetch-input').fill(labelName)
  await expect(page.getByTestId('fetch-hit')).toHaveCount(1)
  await expect(page.getByTestId('fetch-hit')).toContainText('Reference 20:')
  await page.getByTestId('fetch-input').press('Enter')
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(target).toBeInViewport()
  await expect(target).toBeFocused()
  await expect(target).toHaveClass(/selected/)
  await expect(target.locator('.label-chip')).toHaveText(labelName)
  await page.keyboard.press(`${MOD}+z`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(f.toggle).toBeInViewport()
  await expect(f.toggle).toBeFocused()
  await page.keyboard.press(`${MOD}+Shift+z`)
  await expect(f.toggle).toHaveAttribute('aria-expanded', 'true')
})

test('search context drops a cached private ancestor title while independently shared child remains readable', async ({ page, browser }) => {
  const parent = crypto.randomUUID(), child = crypto.randomUUID(), item = crypto.randomUUID(), token = crypto.randomUUID().replaceAll('-', '')
  const secret = `Private ancestor ${crypto.randomUUID().slice(0, 8)}`
  const sharedTitle = `Shared child ${crypto.randomUUID().slice(0, 8)}`
  const response = await postSync(page.request, { data: { changes: [
    { id: parent, patch: { id: parent, kind: 'board', parentId: null, title: secret, icon: 'paw', color: 'none', createdAt: Date.now() } },
    { id: child, patch: { id: child, kind: 'board', parentId: parent, title: sharedTitle, icon: 'paw', color: 'none', createdAt: Date.now(), [`labelName${token}`]: sharedTitle } },
    { id: item, patch: { id: item, kind: 'card', type: 'note', boardId: child, content: { md: 'Independently shared child reference' }, x: 0, y: 0, w: 260, h: 80, z: 1, color: 'none', createdAt: Date.now(), [`label${token}`]: true } },
  ] } })
  expect(response.ok(), await response.text()).toBe(true)
  for (const id of [parent, child]) expect((await page.request.post(`/api/boards/${id}/members`, { data: { username: 'fido', permission: 'view', includeChildren: false } })).status()).toBe(201)
  const context = await browser.newContext({ storageState: { cookies: [], origins: [] }, extraHTTPHeaders: { 'x-doggynote-protocol': '2' } })
  try {
    expect((await context.request.post('/api/auth/login', { data: { username: 'fido', password: 'fetchfetch' } })).ok()).toBe(true)
    const viewer = await context.newPage()
    await viewer.goto(`/#/b/${child}`)
    await expect(cardByText(viewer, 'Independently shared child reference')).toBeVisible()
    await viewer.getByTestId('open-fetch').click()
    await viewer.getByTestId('fetch-input').fill(sharedTitle)
    await expect(viewer.getByTestId('fetch')).toContainText(secret)
    // Keep the prior objects cached while access refreshes independently on jump.
    await viewer.route('**/api/sync?*', (route) => route.abort('internetdisconnected'))
    const members = await (await page.request.get(`/api/shares?boardId=${parent}`)).json()
    expect((await page.request.delete(`/api/boards/${parent}/members/${members.members[0].id}`)).ok()).toBe(true)
    await viewer.getByTestId('fetch-input').press('Enter')
    await expect(viewer.getByTestId('fetch')).toHaveCount(0)
    await viewer.getByTestId('open-fetch').click()
    await viewer.getByTestId('fetch-input').fill(sharedTitle)
    await expect(viewer.getByTestId('fetch-hit').filter({ hasText: 'Independently shared child reference' })).toHaveCount(1)
    await expect(viewer.getByTestId('fetch')).not.toContainText(secret)
  } finally { await context.close() }
})
