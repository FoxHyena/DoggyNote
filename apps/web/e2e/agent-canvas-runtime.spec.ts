test('logout stops local work and saves its partial answer before revoking the session', async ({ page }) => {
  await freshBoard(page, 'Logout cleanup')
  await page.getByTestId('tool-chat').click()
  await page.locator('[data-type="chat"]').getByRole('button', { name: 'Open conversation' }).click()
  const chat = page.getByTestId('chat-conversation')
  await expect(chat).toContainText('Test fixture: no real provider process.')
  await chat.getByRole('textbox', { name: 'Message', exact: true }).fill('Start some work')
  await chat.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__chatFixture.started.length)).toBe(1)
  const run = await page.evaluate(() => (window as any).__chatFixture.started[0])
  await page.evaluate((id) => (window as any).__chatFixture.emit(id, { answer: 'Keep this partial answer.' }), run.runId)
  let revoked = false
  await page.route('**/api/auth/logout', async (route) => {
    expect(await page.evaluate(() => Object.values((window as any).__chatFixture.runs).every((run: any) => run.status !== 'running'))).toBe(true)
    const { API_PORT } = await import('./ports.ts')
    const token = await page.evaluate(() => sessionStorage.getItem('fake-keychain'))
    const saved = await page.request.get(`http://localhost:${API_PORT}/api/chats/${run.chatId}`, { headers: { authorization: `Bearer ${token}`, 'x-doggynote-protocol': '3' } })
    expect((await saved.json()).turns[0]).toMatchObject({ status: 'interrupted', answer: 'Keep this partial answer.' })
    revoked = true
    await route.continue()
  })
  await page.getByTestId('account').click()
  await page.getByTestId('sign-out').click()
  await expect.poll(() => revoked).toBe(true)
  await expect.poll(() => page.evaluate(() => (window as any).__chatFixture.stopped.includes((window as any).__chatFixture.started[0].runId))).toBe(true)
})
