import { expect, test } from '@playwright/test'
import { freshBoard } from './helpers.ts'

test('the creation rail puts everyday cards first and keeps occasional tools available', async ({ page }) => {
  await freshBoard(page)
  const primary = page.getByRole('group', { name: 'Create', exact: true })
  await expect(primary.getByRole('button')).toHaveText(['Note', 'To-do', 'Board'])
  const note = primary.getByTestId('tool-note')
  await expect(note).toHaveClass(/tool-primary/)
  const more = page.getByRole('group', { name: 'More tools', exact: true })
  await expect(more.getByTestId('tool-link')).toBeVisible()
  await more.getByTestId('tool-link').click()
  await expect(page.getByTestId('link-input')).toBeFocused()
  await page.keyboard.press('Escape')
  await note.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('note-editor')).toBeFocused()
})

test('one invitation permission applies to username invites and links', async ({ page }) => {
  await freshBoard(page)
  await page.getByTestId('share').click()
  const panel = page.getByTestId('share-panel')
  await expect(panel.locator('select')).toHaveCount(1)
  const permission = panel.getByLabel('Invitation permission')
  await expect(panel.getByRole('status')).toHaveCount(0)
  await expect(permission).toHaveValue('view')
  expect(await permission.evaluate(el => {
    const control = el.getBoundingClientRect(), caret = el.nextElementSibling!.getBoundingClientRect()
    const css = getComputedStyle(el)
    return Math.abs(control.right - caret.right - parseFloat(css.paddingLeft) - parseFloat(css.borderLeftWidth))
  })).toBeLessThanOrEqual(1)
  await permission.focus()
  await expect(permission).toBeFocused()
  // Native type-ahead works without automating an OS-owned picker popup.
  await page.keyboard.press('c')
  await page.keyboard.press('Tab')
  await expect(permission).toHaveValue('edit')
  await permission.selectOption('edit')
  await expect(page.getByTestId('share-allow-signup')).toBeVisible()
  const invited = page.waitForRequest((r) => r.method() === 'POST' && r.url().includes('/members'))
  await panel.getByLabel('Username to invite').fill('fido')
  await expect(panel.getByRole('button', { name: 'Invite', exact: true })).toHaveClass('primary-btn')
  await expect(page.getByTestId('create-share')).not.toHaveClass('primary-btn')
  await panel.getByRole('button', { name: 'Invite', exact: true }).click()
  expect((await invited).postDataJSON().permission).toBe('edit')
  await expect(panel.getByTestId('share-member').filter({ hasText: 'fido' })).toContainText('Can edit')
  const link = page.waitForRequest((r) => r.method() === 'POST' && r.url().endsWith('/api/shares'))
  await permission.selectOption('view')
  await page.getByTestId('create-share').click()
  expect((await link).postDataJSON().permission).toBe('view')
  await expect(panel.getByRole('region', { name: 'Existing links' })).toContainText('View only')
  await expect(page.getByTestId('share-link')).toContainText('View only')
  await permission.selectOption('edit')
  await expect(page.getByTestId('share-link')).toContainText('View only')
  await expect(page.getByTestId('share-member')).toContainText('Can edit')
})
