import { expect, test } from '@playwright/test'
import { freshBoard, postSync, pullAllObjects, waitForSync } from './helpers.ts'
import { note, seedCards } from './touch.ts'
import { captureSyncedFlow } from './synced-note-shots.ts'

test.use({ actionTimeout: 15_000 })

test('touch creates a synced note on another board, edits it, and unlinks without changing the source', async ({ page }) => {
  test.setTimeout(90_000)
  await freshBoard(page, `Phone overview ${crypto.randomUUID().slice(0, 6)}`)
  const overview = page.url(), boardId = decodeURIComponent(overview.split('/b/')[1]!)
  const research = crypto.randomUUID()
  expect((await postSync(page.request, { data: { changes: [{ id: research, patch: { id: research, kind: 'board', parentId: boardId, title: 'Phone research', icon: 'paw', color: 'none', createdAt: Date.now() } }] } })).ok()).toBe(true)
  const [sourceId] = await seedCards(page, [note('Phone project brief', 0, 0)])
  await page.getByTestId('card').tap()
  await expect(page.getByTestId('card')).toHaveClass(/selected/)
  await page.getByTestId('note-copies').tap()
  const dialog = page.getByRole('dialog', { name: 'Note copies', exact: true })
  await expect(dialog).toBeVisible()
  const box = (await dialog.boundingBox())!, viewport = page.viewportSize()!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(viewport.width)
  const destination = dialog.getByRole('combobox', { name: 'Destination board' })
  expect(await destination.evaluate((el) => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16)
  expect((await dialog.getByTestId('create-synced-copy').boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await destination.selectOption(research)
  await captureSyncedFlow(page, 'phone-research-destination', 'On a phone, the copy dialog explains shared text and local layout with Research selected as the destination.')
  await dialog.getByTestId('create-synced-copy').tap()
  await expect(page.getByTestId('board-name')).toHaveText('Phone research')
  await expect(page.getByTestId('synced-note-hint')).toBeVisible()
  const copyId = await page.getByTestId('card').getAttribute('data-card-id')
  await page.getByTestId('edit-card').tap()
  await expect(page.getByTestId('note-editor')).toBeFocused()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.type('Shared phone revision')
  await page.getByTestId('edit-done').tap()
  await expect(page.getByTestId('note-editor')).toHaveCount(0)
  await waitForSync(page)
  await expect(page.getByTestId('sync-status')).not.toHaveAttribute('aria-label', /Review edits/)
  const saved = await pullAllObjects(page.request)
  const copy = saved.objects.find((o: { id: string }) => o.id === copyId)
  expect(copy?.noteGroupId).toBeTruthy()
  expect(saved.objects.find((o: { id: string }) => o.id === sourceId)).toMatchObject({ noteGroupId: copy.noteGroupId, content: { md: 'Shared phone revision' } })
  await captureSyncedFlow(page, 'phone-updated-shared-brief', 'The edited phone brief has finished saving on the Research board before returning to the overview.')
  await page.goto(overview)
  await expect(page.getByTestId('card')).toContainText('Shared phone revision')
  await expect(page.getByTestId('synced-note-hint')).toBeVisible()
  // Locator touch waits for the card to stop moving after the edit-camera glide.
  // A boundingBox + touchscreen.tap can otherwise use a stale screen position.
  await page.getByTestId('card').tap()
  await expect(page.getByTestId('card')).toHaveClass(/selected/)
  await page.getByTestId('note-copies').tap()
  await dialog.getByTestId('unlink-note').tap()
  await expect(page.getByTestId('synced-note-hint')).toHaveCount(0)
  await page.getByTestId('edit-card').tap()
  await expect(page.getByTestId('note-editor')).toBeFocused()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.type('Independent phone version')
  await page.getByTestId('edit-done').tap()
  await waitForSync(page)
  await page.goto(`/#/b/${research}`)
  await expect(page.getByTestId('card')).toContainText('Shared phone revision')
  await page.reload()
  await expect(page.getByTestId('card')).toContainText('Shared phone revision')
  await expect(page.getByTestId('sync-status')).not.toHaveAttribute('aria-label', /Review edits/)
  const final = await pullAllObjects(page.request)
  expect(final.objects.find((o: { id: string }) => o.id === sourceId)).toMatchObject({ noteGroupId: null, content: { md: 'Independent phone version' } })
  expect(final.objects.find((o: { id: string }) => o.id === copyId)).toMatchObject({ noteGroupId: copy.noteGroupId, content: { md: 'Shared phone revision' } })
  await captureSyncedFlow(page, 'phone-research-after-unlink', 'After the overview instance is unlinked and edited independently, the reopened Research instance retains its shared brief.')
})
