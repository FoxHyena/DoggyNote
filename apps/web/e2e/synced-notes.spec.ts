import { expect, test, type Page } from '@playwright/test'
import { AUTH_FILE } from '../playwright.config.ts'
import { MOD, addNote, cardByText, clickEmpty, dragBy, freshBoard, openParentBoard, postSync, pullAllObjects, waitForSync } from './helpers.ts'
import { captureSyncedFlow } from './synced-note-shots.ts'

test.use({ actionTimeout: 15_000 })

async function editNote(page: Page, text: string, replacement: string) {
  await cardByText(page, text).dblclick()
  await expect(page.getByTestId('note-editor')).toBeVisible()
  await page.keyboard.press(`${MOD}+a`)
  await page.keyboard.type(replacement)
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('note-editor')).toHaveCount(0)
}
async function sync(page: Page) {
  const pulled = page.waitForResponse((r) => r.url().includes('/api/sync?since=') && r.request().method() === 'GET')
  await page.getByTestId('sync-status').click()
  await pulled
  await waitForSync(page)
}
async function setup(page: Page) {
  await freshBoard(page, `Overview ${crypto.randomUUID().slice(0, 6)}`)
  const overviewUrl = page.url()
  await page.getByTestId('tool-board').click()
  await page.keyboard.type('Research sub-board')
  await page.keyboard.press('Enter')
  await cardByText(page, 'Research sub-board').locator('.board-tile').dblclick()
  await expect(page.getByTestId('board-name')).toHaveText('Research sub-board')
  const researchId = page.url().split('/b/')[1]!
  await openParentBoard(page)
  const note = await addNote(page, 'Project brief: warm side lighting.', 0.35, 0.65)
  const originalId = await note.getAttribute('data-card-id')
  await page.getByTestId('note-copies').click()
  await expect(page.getByRole('dialog', { name: 'Note copies' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Destination board' }).selectOption(researchId)
  await captureSyncedFlow(page, 'choose-research-destination', 'Note copies offers a synced or independent version of the project brief, with the Research sub-board selected.')
  await page.getByTestId('create-synced-copy').click()
  await expect(page.getByTestId('board-name')).toHaveText('Research sub-board')
  await expect(page.getByTestId('synced-note-hint')).toHaveText('Synced note · edits update linked notes')
  await waitForSync(page)
  return { overviewUrl, researchId, originalId }
}

test('project brief updates both ways across boards; layout, unlink and ordinary copy stay independent', async ({ page }) => {
  test.setTimeout(90_000)
  const { overviewUrl, originalId } = await setup(page)
  await editNote(page, 'Project brief:', 'Research revision: keep warm side lighting.')
  await waitForSync(page)
  await captureSyncedFlow(page, 'research-updated-brief', 'The Research instance shows the revised brief and the synced-body hint; its layout belongs to this board.')
  await openParentBoard(page)
  await expect(cardByText(page, 'Research revision:')).toBeVisible()
  await captureSyncedFlow(page, 'overview-matching-brief', 'The overview shows the same revised brief beside the Research sub-board, confirming the cross-board update.')
  const original = page.locator(`[data-card-id="${originalId}"]`)
  const originalPosition = await original.evaluate((el) => ({ x: (el as HTMLElement).style.left, y: (el as HTMLElement).style.top }))
  await editNote(page, 'Research revision:', 'Overview revision: agreed opening scene.')
  await cardByText(page, 'Research sub-board').locator('.board-tile').dblclick()
  await expect(cardByText(page, 'Overview revision:')).toBeVisible()
  await dragBy(page, cardByText(page, 'Overview revision:'), 125, 70)
  await waitForSync(page)
  await openParentBoard(page)
  expect(await original.evaluate((el) => ({ x: (el as HTMLElement).style.left, y: (el as HTMLElement).style.top }))).toEqual(originalPosition)
  await original.dblclick()
  await expect(page.getByTestId('note-editor')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('note-editor')).toHaveCount(0)
  await page.getByTestId('note-copies').click()
  await page.getByTestId('create-independent-copy').click()
  const independent = cardByText(page, 'Overview revision:').last()
  await expect(independent.getByTestId('synced-note-hint')).toHaveCount(0)
  await independent.dblclick()
  await expect(page.getByTestId('note-editor')).toBeVisible()
  await page.keyboard.press(`${MOD}+a`)
  await page.keyboard.type('Separate version for another project.')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('note-editor')).toHaveCount(0)
  await expect(cardByText(page, 'Separate version for another project.')).toBeVisible()
  await expect(original).toContainText('Overview revision:')
  await captureSyncedFlow(page, 'independent-version', 'The independent version has different text while the original brief stays linked and unchanged.')
  await cardByText(page, 'Research sub-board').locator('.board-tile').dblclick()
  const linked = cardByText(page, 'Overview revision:')
  await linked.dblclick()
  await expect(page.getByTestId('note-editor')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('note-editor')).toHaveCount(0)
  await page.getByTestId('note-copies').click()
  await page.getByTestId('unlink-note').click()
  await expect(linked.getByTestId('synced-note-hint')).toHaveCount(0)
  await clickEmpty(page)
  await page.keyboard.press(`${MOD}+z`)
  await expect(linked.getByTestId('synced-note-hint')).toBeVisible()
  await page.keyboard.press(`${MOD}+Shift+z`)
  await expect(linked.getByTestId('synced-note-hint')).toHaveCount(0)
  await waitForSync(page)
  await page.reload()
  await expect(cardByText(page, 'Overview revision:')).toBeVisible()
  await page.goto(overviewUrl)
  await expect(cardByText(page, 'Separate version')).toBeVisible()
})

test('authorized sessions survive offline body edits, deletion/restore and body Undo without group loss', async ({ page, context, browser }) => {
  test.setTimeout(90_000)
  const { overviewUrl } = await setup(page)
  const otherContext = await browser.newContext({ storageState: AUTH_FILE })
  try {
    const other = await otherContext.newPage()
    await other.goto(overviewUrl)
    await expect(cardByText(other, 'Project brief:')).toBeVisible()
    await context.setOffline(true)
    await editNote(page, 'Project brief:', 'Offline research revision.')
    await expect(page.getByTestId('sync-status')).toHaveAttribute('data-pending', /[1-9]/)
    await context.setOffline(false)
    await sync(page)
    await sync(other)
    await expect(cardByText(other, 'Offline research revision.')).toBeVisible()
    await clickEmpty(page)
    await page.keyboard.press(`${MOD}+z`)
    await expect(cardByText(page, 'Project brief:')).toBeVisible()
    await waitForSync(page)
    await sync(other)
    await expect(cardByText(other, 'Project brief:')).toBeVisible()
    await page.keyboard.press(`${MOD}+Shift+z`)
    await expect(cardByText(page, 'Offline research revision.')).toBeVisible()
    await cardByText(page, 'Offline research revision.').dblclick()
    await expect(page.getByTestId('note-editor')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('note-editor')).toHaveCount(0)
    await page.keyboard.press('Delete')
    await expect(page.getByTestId('card')).toHaveCount(0)
    await waitForSync(page)
    await editNote(other, 'Offline research revision.', 'Still here after deleting one instance.')
    await waitForSync(other)
    await sync(page)
    await page.getByTestId('tool-trash').click()
    await expect(page.getByTestId('trash-item')).toContainText('Still here after deleting one instance.')
    await page.getByTestId('restore').click()
    await expect(cardByText(page, 'Still here after deleting one instance.')).toBeVisible()
    await waitForSync(page)
    await page.reload()
    await expect(cardByText(page, 'Still here after deleting one instance.').getByTestId('synced-note-hint')).toBeVisible()
  } finally { await context.setOffline(false); await otherContext.close() }
})

test('conflicting offline sessions converge in acceptance order and body Undo keeps their cross-board links', async ({ page, context, browser }) => {
  test.setTimeout(90_000)
  const { overviewUrl, originalId } = await setup(page)
  const researchId = await cardByText(page, 'Project brief:').getAttribute('data-card-id')
  const otherContext = await browser.newContext({ storageState: AUTH_FILE })
  try {
    const other = await otherContext.newPage()
    await other.goto(overviewUrl)
    await expect(cardByText(other, 'Project brief:')).toBeVisible()
    await Promise.all([context.setOffline(true), otherContext.setOffline(true)])
    await editNote(page, 'Project brief:', 'Research session revision.')
    await editNote(other, 'Project brief:', 'Overview session revision.')
    await expect(page.getByTestId('sync-status')).toHaveAttribute('data-pending', /[1-9]/)
    await expect(other.getByTestId('sync-status')).toHaveAttribute('data-pending', /[1-9]/)

    await context.setOffline(false)
    await sync(page)
    let snapshot = await pullAllObjects(page.request)
    for (const id of [originalId, researchId]) expect(snapshot.objects.find((o: { id: string }) => o.id === id)).toMatchObject({ content: { md: 'Research session revision.' } })

    await otherContext.setOffline(false)
    await sync(other)
    await sync(page)
    await expect(cardByText(page, 'Overview session revision.')).toBeVisible()
    await expect(cardByText(other, 'Overview session revision.')).toBeVisible()
    snapshot = await pullAllObjects(page.request)
    const linked = snapshot.objects.filter((o: { id: string }) => o.id === originalId || o.id === researchId)
    expect(linked).toHaveLength(2)
    expect(linked[0].noteGroupId).toBeTruthy()
    expect(linked[0].noteGroupId).toBe(linked[1].noteGroupId)
    const group = linked[0].noteGroupId

    await clickEmpty(other)
    await other.keyboard.press(`${MOD}+z`)
    await expect(cardByText(other, 'Project brief:')).toBeVisible()
    await waitForSync(other)
    await sync(page)
    await expect(cardByText(page, 'Project brief:')).toBeVisible()
    snapshot = await pullAllObjects(page.request)
    for (const id of [originalId, researchId]) expect(snapshot.objects.find((o: { id: string }) => o.id === id)).toMatchObject({ noteGroupId: group, content: { md: 'Project brief: warm side lighting.' } })
  } finally {
    await Promise.all([context.setOffline(false), otherContext.setOffline(false)])
    await otherContext.close()
  }
})

test('a protected cross-board body remains selectable and can be unlinked without exposing or changing its hidden partner', async ({ page, browser, baseURL }) => {
  test.setTimeout(60_000)
  const visible = crypto.randomUUID(), hidden = crypto.randomUUID(), first = crypto.randomUUID(), second = crypto.randomUUID(), group = crypto.randomUUID()
  const hiddenTitle = `Private research ${crypto.randomUUID()}`
  const boards = [[visible, 'Accessible project brief'], [hidden, hiddenTitle]].map(([id, title]) => ({ id: id!, patch: { id, kind: 'board', parentId: null, title, icon: 'paw', color: 'none', createdAt: Date.now() } }))
  const notes = [[first, visible], [second, hidden]].map(([id, boardId]) => ({ id: id!, patch: { id, kind: 'card', type: 'note', boardId, x: 0, y: 0, w: 280, h: 80, z: 1, color: 'none', noteGroupId: group, content: { md: 'Protected shared brief' }, createdAt: Date.now() } }))
  expect((await postSync(page.request, { data: { changes: [...boards, ...notes] } })).ok()).toBe(true)
  expect((await page.request.post(`/api/boards/${visible}/members`, { data: { username: 'fido', permission: 'edit', includeChildren: false } })).status()).toBe(201)
  const guest = await browser.newContext({ storageState: { cookies: [], origins: [] }, extraHTTPHeaders: { 'x-doggynote-protocol': '2' } })
  try {
    expect((await guest.request.post(`${baseURL}/api/auth/login`, { data: { username: 'fido', password: 'fetchfetch' } })).ok()).toBe(true)
    const view = await guest.newPage()
    await view.goto(`${baseURL}/#/b/${visible}`)
    const card = view.locator(`[data-card-id="${first}"]`)
    await expect(card.getByTestId('synced-note-hint')).toHaveText('Synced note · read-only body')
    await card.click()
    await expect(card).toHaveClass(/selected/)
    await expect(view.getByTestId('note-editor')).toHaveCount(0)
    await view.getByTestId('note-copies').click()
    const dialog = view.getByRole('dialog', { name: 'Note copies', exact: true })
    await expect(dialog.getByTestId('create-synced-copy')).toBeDisabled()
    await expect(dialog).not.toContainText(hiddenTitle)
    await captureSyncedFlow(view, 'protected-body-actions', 'A protected shared body allows a separate version or unlinking without exposing its other location.')
    await dialog.getByTestId('unlink-note').click()
    await expect(card.getByTestId('synced-note-hint')).toHaveCount(0)
    await card.dblclick()
    await expect(view.getByTestId('note-editor')).toBeVisible()
    await view.keyboard.press(`${MOD}+a`)
    await view.keyboard.type('Independent accessible version')
    await view.keyboard.press('Escape')
    await expect(view.getByTestId('note-editor')).toHaveCount(0)
    await waitForSync(view)
    const { objects } = await pullAllObjects(page.request)
    expect(objects.find((o: { id: string }) => o.id === first)).toMatchObject({ noteGroupId: null, content: { md: 'Independent accessible version' } })
    expect(objects.find((o: { id: string }) => o.id === second)).toMatchObject({ noteGroupId: group, content: { md: 'Protected shared brief' } })
  } finally { await guest.close() }
})
